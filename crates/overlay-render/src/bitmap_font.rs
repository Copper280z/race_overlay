//! Tiny 5x7 bitmap font. Keeping glyphs in source avoids platform font fallback.
use crate::Rgba;
use tiny_skia::{Paint, Pixmap, Rect, Transform};

pub fn draw_char(pm: &mut Pixmap, x: f32, y: f32, size: f32, ch: char, color: Rgba) -> f32 {
    let glyph = glyph(ch);
    let scale = (size / 7.).max(0.5);
    let mut paint = Paint::default();
    paint.set_color(color.sk());
    paint.anti_alias = false;
    for (row, bits) in glyph.iter().enumerate() {
        for col in 0..5 {
            if bits & (1 << (4 - col)) != 0
                && let Some(r) = Rect::from_xywh(
                    x + col as f32 * scale,
                    y + row as f32 * scale,
                    scale.ceil(),
                    scale.ceil(),
                )
            {
                pm.fill_rect(r, &paint, Transform::identity(), None)
            }
        }
    }
    6.
}
